/**
 * Assemble `client.js` from the plain ESM modules in `src/`.
 *
 * Why a local assembler instead of a bundler: the browser artifact is one
 * classic script that registers a factory through `window.__ModuleLoader__`,
 * while the same logic has to stay importable by `node --test`. A full bundler
 * would add a build dependency to a package that must install into a clean DSH
 * with no install step at all, so the transform is deliberately tiny and
 * checked:
 *
 * - single-line and multi-line `import` statements are dropped;
 * - top-level `export ` prefixes are dropped;
 * - every module body lands in the factory closure, so the modules share one
 *   scope and their top-level names must not collide;
 * - the result is syntax-checked, and `--check` fails when the committed
 *   `client.js` is stale.
 *
 * The accepted subset is documented in `README.md`; the build refuses anything
 * outside it rather than emitting a broken bundle.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const packageJson = JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8'));

/** Emission order: leaves first, the entry last. */
const MODULES = ['materials.js', 'model.js', 'render.js', 'focus.js', 'client-entry.js'];

const HEADER = `// @dsh-llsa/hud — browser half. GENERATED by scripts/build-client.mjs from src/*.js.
// Do not edit by hand: run \`npm run build\` in packages/hud (a test fails on drift).
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory(require) {
    const React = require('react');
`;

const FOOTER = `
    return {
      inject: ['slots'],
      apply(ctx) {
        return applyClient(ctx, React);
      },
    };
  },
});
`;

/** Strip the line-oriented import block, keeping every other line verbatim. */
function stripImports(source) {
  const lines = source.split('\n');
  const kept = [];
  let inside = false;
  for (const line of lines) {
    const trimmed = line.trimStart();
    if (!inside) {
      if (/^import\s/.test(trimmed) && !/^import\s*\(/.test(trimmed)) {
        inside = !trimmed.endsWith(';');
        continue;
      }
      kept.push(line);
      continue;
    }
    if (trimmed.endsWith(';')) inside = false;
  }
  return kept.join('\n');
}

/** Drop the `export ` prefix; refuse unsupported forms loudly. */
function stripExports(source, file) {
  if (/^\s*export\s+default\b/m.test(source)) throw new Error(`${file}: default exports are not part of the bundle subset`);
  if (/^\s*export\s*\{/m.test(source)) throw new Error(`${file}: named export lists are not part of the bundle subset`);
  if (/^\s*export\s+\*/m.test(source)) throw new Error(`${file}: re-exports are not part of the bundle subset`);
  return source.replace(/^(\s*)export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gm, '$1');
}

/** Top-level declarations, used for the one-scope collision check. */
function topLevelNames(source) {
  const names = [];
  const regex = /^(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;
  let match = regex.exec(source);
  while (match !== null) {
    names.push(match[1]);
    match = regex.exec(source);
  }
  return names;
}

/** Build the bundle text. Pure: same inputs, same bytes. */
export function buildBundle() {
  const seen = new Map();
  const parts = [];
  for (const file of MODULES) {
    const path = resolve(packageRoot, 'src', file);
    if (!existsSync(path)) throw new Error(`missing module: ${file}`);
    const original = readFileSync(path, 'utf8');
    const withoutImports = stripImports(original);
    const body = stripExports(withoutImports, file).trimEnd();
    for (const name of topLevelNames(body)) {
      if (seen.has(name)) throw new Error(`duplicate top-level name "${name}" in ${file} (first in ${seen.get(name)})`);
      seen.set(name, file);
    }
    parts.push(`    // ---- src/${file} ----\n${body}\n`);
  }
  const bundle = `${HEADER}${parts.join('\n')}${FOOTER}`;
  if (/^\s*(?:import|export)\s/m.test(bundle)) throw new Error('bundle still contains an import/export statement');
  // Compiling proves the factory body parses; it is never executed here.
  new Function(bundle);
  return bundle;
}

/** `data/tool-aliases-v1.json` is generated from `src/materials.js`. */
export async function buildAliasTable() {
  const { aliasTable } = await import(new URL('../src/materials.js', import.meta.url).href);
  return `${JSON.stringify(aliasTable(), null, 2)}\n`;
}

/** CLI entry: `node scripts/build-client.mjs [--check]`. */
async function main() {
  const clientPath = resolve(packageRoot, 'client.js');
  const aliasesPath = resolve(packageRoot, 'data/tool-aliases-v1.json');
  const bundle = buildBundle();
  const aliases = await buildAliasTable();

  if (process.argv.includes('--check')) {
    const currentClient = existsSync(clientPath) ? readFileSync(clientPath, 'utf8') : '';
    const currentAliases = existsSync(aliasesPath) ? readFileSync(aliasesPath, 'utf8') : '';
    const stale = currentClient !== bundle || currentAliases !== aliases;
    if (stale) {
      console.error('client.js or data/tool-aliases-v1.json is stale: run `npm run build` in packages/hud');
      process.exitCode = 1;
    } else {
      console.log('bundle is up to date');
    }
    return;
  }
  writeFileSync(clientPath, bundle, 'utf8');
  writeFileSync(aliasesPath, aliases, 'utf8');
  console.log(`wrote client.js (${bundle.length} bytes) and data/tool-aliases-v1.json`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
